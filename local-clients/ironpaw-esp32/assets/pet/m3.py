"""The 3D-rendered dog (`3d/`) as the board's sprite sheet.

`3d/sprites.py` writes 200x200 GIFs (40x40 pixel art at x5, 16 frames each) over a dark blue
background into `3d/frames/`. This takes them back to 40x40, makes the background transparent,
pools every colour into one palette and writes `sheet.idx` plus `../../src/pet_data.rs`.

    python3 m3.py [3d/frames]
"""

import sys
from pathlib import Path

from PIL import Image

OUT = Path(__file__).parent
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else OUT / "3d" / "frames"
CELL, SCALE = 40, 5
BG = (16, 40, 72)
# Board mood -> 3D state.
MOODS = {
    "IDLE": "idle",
    "HAPPY": "happy",
    "SLEEP": "sleep",
    "SAD": "sad",
    "LISTENING": "listening",
    "THINKING": "thinking",
    "TALKING": "talking",
    "EATING": "hungry",
}


def frames(name):
    im = Image.open(SRC / f"{name}.gif")
    out = []
    for i in range(im.n_frames):
        im.seek(i)
        rgb = im.convert("RGB")
        # Nearest: the centre pixel of every 5x5 block.
        small = Image.new("RGB", (CELL, CELL))
        px, sp = rgb.load(), small.load()
        for y in range(CELL):
            for x in range(CELL):
                sp[x, y] = px[x * SCALE + SCALE // 2, y * SCALE + SCALE // 2]
        out.append((small, im.info.get("duration", 150)))
    return out


def is_bg(p):
    return max(abs(a - b) for a, b in zip(p, BG)) <= 12


states = {mood: frames(name) for mood, name in MOODS.items()}
per_row = max(len(fs) for fs in states.values())
sheet_w, sheet_h = per_row * CELL, len(states) * CELL
full = Image.new("RGB", (sheet_w, sheet_h), BG)
rows = []
for row, (mood, fs) in enumerate(states.items()):
    cells = []
    for col, (im, ms) in enumerate(fs):
        full.paste(im, (col * CELL, row * CELL))
        cells.append((col * CELL, row * CELL, ms))
    rows.append((mood, cells))

# One palette for every state: the GIFs were quantized one by one (16 colours each, ~360 in
# all), so pool them and quantize once more. 63 + transparent fits a byte with room to spare.
# ponytail: 63 colours; lower it for a flatter look.
COLOURS = 63
quant = full.quantize(COLOURS, dither=Image.NONE)
raw = quant.getpalette()[: COLOURS * 3]
palette = [tuple(raw[i : i + 3]) for i in range(0, len(raw), 3)]
qpx, fpx = quant.load(), full.load()
idx = bytearray(sheet_w * sheet_h)
for y in range(sheet_h):
    for x in range(sheet_w):
        if not is_bg(fpx[x, y]):
            idx[y * sheet_w + x] = qpx[x, y] + 1

(OUT / "sheet.idx").write_bytes(idx)

lines = [
    "// Generated by assets/pet/m3.py from assets/pet/3d/frames (the 3D dog): do not edit.",
    "",
    "/// sRGB; index 0 is transparent and unused.",
    f"pub const PALETTE: [(u8, u8, u8); {len(palette) + 1}] = [{', '.join(str(p) for p in [(0, 0, 0)] + palette)}];",
    f"pub const CELL: u32 = {CELL};",
    f"pub const SHEET_W: u32 = {sheet_w};",
    "/// Cell origin in the sheet and how long the frame shows.",
    "pub struct Frame { pub x: u16, pub y: u16, pub ms: u16 }",
    "",
]
for mood, cells in rows:
    lines.append(f"pub const {mood}: &[Frame] = &[")
    for ox, oy, ms in cells:
        lines.append(f"    Frame {{ x: {ox}, y: {oy}, ms: {ms} }},")
    lines.append("];")
    lines.append("")
(OUT.parent.parent / "src" / "pet_data.rs").write_text("\n".join(lines))

# Self-check: every state has frames, nothing is fully transparent, the sheet matches.
assert all(cells for _, cells in rows)
assert idx.count(0) < len(idx) * 0.9, "sprites look empty: wrong background colour?"
assert len(idx) == sheet_w * sheet_h
print(f"{len(rows)} moods, {len(palette)} colours, sheet {sheet_w}x{sheet_h}")
